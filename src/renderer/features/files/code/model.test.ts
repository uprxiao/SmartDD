import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { codeLanguage, highlightRanges, highlightWindow, highlightCode, CODE_LIMITS, CODE_TOKEN_STRIDE, codeTokenStyle } from './model';
// @ts-expect-error The themes are immutable JS data shared with the prototype.
import { CODE_THEMES } from './themes.mjs';

function pieces(source: string, filename: string) {
  const tokens = highlightRanges(source, filename), out: { text: string; light: number; dark: number }[] = [];
  for (let i = 0; i < tokens.length; i += CODE_TOKEN_STRIDE) out.push({ text: source.slice(tokens[i], tokens[i + 1]), light: tokens[i + 2], dark: tokens[i + 3] });
  return out;
}
describe('shared TextMate tokenization and verified reference colors', () => {
  it('keeps the complete 245 public-derived scope rules equal to the statically observed reference colors', () => {
    // Hashes cover the independently observed reference tokenColors, not output generated by this test.
    for (const [mode, digest] of [['light', 'f35c7b53bfa2a86babdb0dfffa89620728a55c86a63b6ba521a3692de62892bf'], ['dark', 'c6c92a4904eedc328132811ae68e06e28ec508a61976b672b7d8b42394af42cb']]) {
      expect(CODE_THEMES[mode].tokenColors).toHaveLength(245);
      expect(createHash('sha256').update(JSON.stringify(CODE_THEMES[mode].tokenColors)).digest('hex')).toBe(digest);
    }
  });
  it('uses independent light/dark reference colors for TypeScript syntax instead of inferred roles', () => {
    const source = `import x from '<script>🙂</script>';\nconst baseURL = 42; // keep`;
    const tokens = pieces(source, 'playwright.config.ts');
    for (const item of [
      { text: 'import', light: 0xd53538, dark: 0xf67576 },
      { text: 'const', light: 0x751ed9, dark: 0xb06dff },
      { text: 'baseURL', light: 0xbd5800, dark: 0xfa994c },
      { text: "'<script>🙂</script>'", light: 0x008809, dark: 0x85df7b },
      { text: '42', light: 0x0071ea, dark: 0x6dcbf4 },
      { text: '// keep', light: 0x666666, dark: 0x999999 },
    ]) expect(tokens).toContainEqual(item);
  });
  it('preserves CRLF, Unicode, multiline lexical state and source offsets', () => {
    const source = '/* start\r\nconst inside = "🟢<&amp;";\r\nend */\nconst outside = 42;';
    const tokens = highlightRanges(source, 'fixture.ts');
    for (let i = 0; i < tokens.length; i += CODE_TOKEN_STRIDE) {
      expect(tokens[i]).toBeLessThan(tokens[i + 1]); expect(tokens[i + 1]).toBeLessThanOrEqual(source.length);
      if (i) expect(tokens[i]).toBeGreaterThanOrEqual(tokens[i - CODE_TOKEN_STRIDE + 1]);
    }
    const inside = source.indexOf('inside'), token = pieces(source, 'fixture.ts').find(t => t.text.includes('inside'));
    expect(token?.dark).toBe(0x999999);
    const window = highlightWindow(tokens, inside, inside + 4);
    expect(window.length).toBe(CODE_TOKEN_STRIDE); expect(window[3]).toBe(0x999999);
  });
  it('honors exact filename, compound suffix, original-case collisions and complete grammar IDs', () => {
    for (const [name, language] of [['pom.xml', 'xml'], ['Main.java', 'java'], ['main.py', 'python'], ['run.sh', 'zsh'], ['.env', 'dotenv'], ['Dockerfile', 'dockerfile'], ['CMakeLists.txt', 'cmake'], ['Gemfile', 'ruby'], ['main.component.ts', 'angular-ts'], ['main.tsx', 'tsx'], ['sample.P', 'prolog'], ['sample.p', 'pascal'], ['x.wy', '文言']]) expect(codeLanguage(name)).toBe(language);
    expect(codeLanguage('notes.txt')).toBeNull(); expect(codeLanguage('unknown.nonesuch')).toBeNull();
    expect(pieces('public class Demo { String name = "value"; }', 'Demo.java').some(v => v.text.includes('"value"') && v.dark === 0x85df7b)).toBe(true);
    expect(pieces('set(NAME "value")', 'CMakeLists.txt').some(v => v.dark !== 0xfcfcfc)).toBe(true);
  });
  it('F09 resolves registered extensionless names to their real syntax grammars', () => {
    for (const [name, language, source] of [['Makefile', 'makefile', 'all:\n\t@true\n'], ['Dockerfile', 'dockerfile', 'FROM scratch\n']]) {
      expect(codeLanguage(name)).toBe(language);
      expect(pieces(source, name).some(token => token.dark !== 0xfcfcfc)).toBe(true);
    }
    expect(codeLanguage('empty')).toBeNull(); expect(codeLanguage('unknown.ext')).toBeNull();
  });
  it('bounds window output and rejects invalid paint fields and oversized sources', () => {
    const large = new Uint32Array((CODE_LIMITS.window + 10) * CODE_TOKEN_STRIDE);
    for (let i = 0; i < large.length / CODE_TOKEN_STRIDE; i++) large.set([i * 2, i * 2 + 1, 0x112233, 0x445566, 0, 0], i * CODE_TOKEN_STRIDE);
    expect(highlightWindow(large, 0, large.length).length).toBe(CODE_LIMITS.window * CODE_TOKEN_STRIDE);
    expect(highlightWindow(large, 200, 210)[0]).toBe(200);
    expect(() => highlightRanges('x'.repeat(CODE_LIMITS.source + 1), 'x.js')).toThrow('20 MiB');
    expect(() => codeTokenStyle(new Uint32Array([0, 1, 0xffffffff, 0, 0, 0]), 0)).toThrow('color');
    expect(() => codeTokenStyle(new Uint32Array([0, 1, 0, 0, 16, 0]), 0)).toThrow('font');
    expect(codeTokenStyle(new Uint32Array([0, 1, 0, 0, 15, 0]), 0)).toContain('--fw-token-light-decoration:underline line-through');
    expect(codeTokenStyle(new Uint32Array([0, 1, 0, 0, 0, 0]), 0)).toBe('--fw-token-light:#000000;--fw-token-dark:#000000');
  });
  it('shares escaped dual-theme tokens with Markdown and Notebook without changing source text', () => {
    const source = 'import x from "<script>🙂</script>";\nconst 中文 = 42; // keep';
    const result = highlightCode(source, 'ts');
    expect(result.language).toBe('typescript');
    expect(result.html).toContain('class="fw-code-token"');
    expect(result.html).toContain('--fw-token-dark:#f67576');
    expect(result.html).toContain('&lt;script&gt;🙂&lt;/script&gt;'); expect(result.html).not.toContain('<script>');
    const recovered = result.html!.replace(/<span class="fw-code-token" style="[^"]*">|<\/span>/g, '').replace(/&(?:amp|lt|gt|quot|#39);/g, value => ({ '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" })[value]!);
    expect(recovered).toBe(source);
    expect(highlightCode(source, 'not-a-language')).toEqual({ html: null, language: null });
  });
});
