import assert from 'node:assert/strict';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

// The product intentionally does not inspect an actual login in SMARTDD_CLI_HOME.
// These are a normal, public local Magpie preset and an isolated managed profile.
export const modelOrigin='http://127.0.0.1:3425', publicToken='magpie-claude';
export const modelPort=3425;
export function requireOwnDetectedClaude(detection, wrapper) {
  const t=detection.tool;
  assert.equal(detection.error,null);
  assert(t.installed===true && t.login==='none' && t.kind==='claude' && t.version==='2.1.329');
  assert.equal(t.executable,wrapper);assert.equal(t.customPath,wrapper);
  return t;
}

export function ownProviderInput(model) {
  return {name:'M16 local isolated model fixture',preset:'magpie',authType:'api-key',
    endpoints:{anthropic:modelOrigin+'/'},models:[{id:model,name:model,contextWindow:null,
      offline:false,availability:{claude:'untested',codex:'untested',antigravity:'untested'}}]};
}

export function ownManagedRoot(data, profileId) {
  assert(/^[a-f0-9-]{36}$/i.test(profileId));
  return join(data,'agents','claude',createHash('sha256').update(profileId).digest('hex').slice(0,32));
}

export function isOwnProbe(body, model, stage, active) {
  return stage==='setup-own-provider'&&!active&&body.model===model&&body.stream===true&&
    body.tools?.length===1&&body.tools[0].name==='wy_ping'&&
    body.tools[0].input_schema?.type==='object';
}

export function ownWrapper({data,root,cliHome,tmp,cli,model,proxy}) {
  assert(data===join(root,'data')&&cliHome===join(root,'cli-home')&&tmp===join(root,'tmp'));
  const q=s=>"'"+s.replaceAll("'","'\\''")+"'";
  const expected=join(root,'managed-claude-path');
  const env={HOME:cliHome,PATH:'/usr/bin:/bin:/usr/sbin:/sbin',TMPDIR:tmp,SHELL:'/bin/zsh',
    LANG:'en_US.UTF-8',CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:'1',
    DISABLE_TELEMETRY:'1',DISABLE_ERROR_REPORTING:'1',...proxy};
  const fixed=Object.entries(env).map(([k,v])=>q(k+'='+v)).join(' ');
  // Version detection is unauthed and stays isolated. Real model launches use the
  // exact managed configuration generated by the product, never a fabricated login.
  // Prevent accidental interaction with any host account/other endpoint.
  return '#!/bin/sh\nset -eu\n'+
    'if [ "$#" -eq 1 ] && [ "$1" = --version ]; then\n'+
    '  exec /usr/bin/env -i '+fixed+' '+q('CLAUDE_CONFIG_DIR='+join(cliHome,'.claude'))+' '+q(cli)+' "$@"\nfi\n'+
    'expected=$(/bin/cat '+q(expected)+') || exit 64\n'+
    '[ "${CLAUDE_CONFIG_DIR-}" = "$expected" ] || exit 64\n'+
    '[ "${ANTHROPIC_BASE_URL-}" = '+q(modelOrigin+'/')+' ] || [ "${ANTHROPIC_BASE_URL-}" = '+q(modelOrigin)+' ] || exit 64\n'+
    '[ "${ANTHROPIC_API_KEY-}" = '+q(publicToken)+' ] || exit 64\n'+
    '[ "${ANTHROPIC_MODEL-}" = '+q(model)+' ] || exit 64\n'+
    'exec /usr/bin/env -i '+fixed+' "CLAUDE_CONFIG_DIR=$CLAUDE_CONFIG_DIR" "ANTHROPIC_BASE_URL=$ANTHROPIC_BASE_URL" "ANTHROPIC_API_KEY=$ANTHROPIC_API_KEY" "ANTHROPIC_MODEL=$ANTHROPIC_MODEL" '+
    ["ANTHROPIC_DEFAULT_OPUS_MODEL","ANTHROPIC_DEFAULT_SONNET_MODEL","ANTHROPIC_DEFAULT_HAIKU_MODEL","ANTHROPIC_DEFAULT_FABLE_MODEL","ANTHROPIC_SMALL_FAST_MODEL","CLAUDE_CODE_SUBAGENT_MODEL"].map(k=>`"${k}=\${${k}:-$ANTHROPIC_MODEL}"`).join(' ')+
    ' '+q('CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL=1')+' '+q('CLAUDE_CODE_DISABLE_1M_CONTEXT=1')+' '+q('CLAUDE_CODE_ADDITIONAL_DIRECTORIES_CLAUDE_MD=1')+' '+q(cli)+' "$@"\n';
}
