import { spawn } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ExperimentBroker } from '../cli-identity/broker.mjs';
const here = dirname(fileURLToPath(import.meta.url));
const mode = process.argv[2] || 'read-only', tag = process.argv[3] || mode;
const cfgTemplates = JSON.parse(process.env.S0A_CFG || '[]');
const broker = new ExperimentBroker(); await broker.start();
const run = broker.issue('A', ['read'], 300000);
const work = mkdtempSync(join(tmpdir(), 'wy-s0a-'));
const env = { ...process.env, PATH: join(here, 'bin') + ':' + process.env.PATH, WILLYOU_RUN_TOKEN: run.token, WILLYOU_RUN_CRED: run.token, WILLYOU_ENDPOINT: broker.endpoint };
const prompt = '只执行下面这一条 shell 命令一次，不要做别的事，然后把它的 stdout 原样输出：willyou-probe';
const cfg = cfgTemplates.map(x => x.replaceAll('<SOCK>', broker.endpoint));
const args = ['exec', '--json', '--ephemeral', '--skip-git-repo-check', '-C', work, ...(mode === 'none' ? [] : ['-s', mode]), ...cfg.flatMap(x => ['-c', x]), prompt];
const t0 = Date.now(); const events = []; let err = '';
const p = spawn('codex', args, { env, stdio: ['ignore', 'pipe', 'pipe'] });
let buf = ''; p.stdout.on('data', d => { buf += d; let i; while ((i = buf.indexOf('\n')) >= 0) { const l = buf.slice(0, i); buf = buf.slice(i + 1); try { events.push(JSON.parse(l)); } catch {} } });
p.stderr.on('data', d => err += d);
const timer = setTimeout(() => p.kill('SIGTERM'), 180000);
const code = await new Promise(r => p.on('close', r)); clearTimeout(timer);
const cmds = events.filter(e => JSON.stringify(e).includes('willyou-probe'));
const probeOut = events.map(e => JSON.stringify(e)).join('\n').match(/\{\\"probe\\":\\"s0a\\".*?\}\\n/g) || [];
const result = { mode, tag, cfgTemplates, codexExit: code, seconds: Math.round((Date.now() - t0) / 1000), eventCount: events.length, brokerCalls: broker.calls, probeReports: probeOut.map(s => JSON.parse(JSON.parse('"' + s.replace(/\\n$/, '') + '"'))), stderrTail: err.replaceAll(broker.endpoint, '<sock>').slice(-400), commandEvents: cmds.slice(0, 4).map(e => JSON.stringify(e).slice(0, 600)) };
result.leakCheck = !JSON.stringify(result).includes(run.token) && !JSON.stringify(events).includes(run.token);
mkdirSync(join(here, 'results'), { recursive: true });
writeFileSync(join(here, 'results', `codex-0.166.0-exec-${tag}.json`), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({ tag, stderrTail: result.stderrTail, codexExit: code, seconds: result.seconds, brokerCalls: broker.calls.length, probeReports: result.probeReports, leakCheck: result.leakCheck }, null, 1));
await broker.close(); process.exit(0);
